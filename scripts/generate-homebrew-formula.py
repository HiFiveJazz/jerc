#!/usr/bin/env python3
"""Generate a checksum-pinned Homebrew tap formula from Jerc macOS archives.

The archives are produced by scripts/package_release.py. The published formula
uses GitHub Release URLs; --local-assets changes only the URLs for pre-release
installation smoke tests, so they never rely on as-yet-unpublished downloads.
"""

import argparse
import hashlib
import re
import tarfile
from pathlib import Path

TARGETS = {
    "arm": "aarch64-apple-darwin",
    "intel": "x86_64-apple-darwin",
}
REPO = "https://github.com/HiFiveJazz/jerc"


def archives_for(tag: str, directory: Path) -> dict[str, Path]:
    if not re.fullmatch(r"v\d+\.\d+\.\d+", tag):
        raise ValueError(f"Invalid stable release tag: {tag!r}")
    result = {}
    for arch, target in TARGETS.items():
        archive = directory / f"jerc-{tag}-{target}.tar.gz"
        if not archive.is_file():
            raise FileNotFoundError(f"Missing macOS release archive: {archive}")
        root = f"jerc-{tag}-{target}"
        with tarfile.open(archive, "r:gz") as contents:
            binary = next((m for m in contents.getmembers() if m.name == f"{root}/jerc"), None)
            if binary is None or not binary.isfile() or not (binary.mode & 0o111):
                raise ValueError(f"Archive has no executable {root}/jerc: {archive}")
            for expected in ("LICENSE", "README.md", "config.example.toml"):
                if not any(m.name == f"{root}/{expected}" and m.isfile() for m in contents.getmembers()):
                    raise ValueError(f"Archive missing {root}/{expected}: {archive}")
        result[arch] = archive
    return result


def generate(tag: str, directory: Path, local_assets: bool = False) -> str:
    archives = archives_for(tag, directory)
    version = tag[1:]

    def stanza(arch: str) -> str:
        target = TARGETS[arch]
        archive = archives[arch]
        url = archive.resolve().as_uri() if local_assets else f"{REPO}/releases/download/{tag}/{archive.name}"
        with archive.open("rb") as stream:
            digest = hashlib.file_digest(stream, "sha256").hexdigest()
        return f'''    on_{arch} do
      url "{url}"
      sha256 "{digest}"
    end'''

    return f'''# Generated by scripts/generate-homebrew-formula.py; do not hand-edit.
# Copy Formula/jerc.rb into a Homebrew tap after the GitHub Release exists.
class Jerc < Formula
  desc "Keyboard-driven terminal email client written in Rust"
  homepage "{REPO}"
  version "{version}"
  license "GPL-3.0-only"
  depends_on :macos

  on_macos do
{stanza("arm")}

{stanza("intel")}
  end

  def install
    executables = Dir["**/jerc"].select {{ |path| File.file?(path) }}
    raise "Expected exactly one Jerc executable in the release archive" unless executables.length == 1

    bin.install executables.first
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/jerc --version")
  end
end
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tag", required=True)
    parser.add_argument("--archives", type=Path, default=Path("dist"))
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--local-assets", action="store_true", help="use file:// URLs for macOS CI smoke tests")
    args = parser.parse_args()
    try:
        result = generate(args.tag, args.archives, args.local_assets)
    except (ValueError, FileNotFoundError, tarfile.TarError) as error:
        parser.error(str(error))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(result, encoding="utf-8")
    print(f"Created {args.output}")


if __name__ == "__main__":
    main()
